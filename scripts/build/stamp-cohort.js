#!/usr/bin/env node
/**
 * Stamp the cohort JWT into lib/cohort/build-info.js.
 *
 * Reads the ECDSA private key from ~/.config/robotdojo-build/cohort-priv.pem
 * (never committed — release machine only), computes the current ISO week,
 * signs `{week, exp: now + 180d}` as ES256, and writes a small module:
 *
 *   export const BB_COHORT_WEEK   = '2026-W20';
 *   export const BB_VALID_UNTIL   = '2026-08-12T15:00:00Z';
 *   export const BB_COHORT_JWT    = 'eyJhbGciOiJFUzI1NiIs...';
 *
 * This file is .gitignored — generated fresh on every release. Run before
 * publishing apps/static/install.sh so the cohort is stamped into the
 * artifact a stranger downloads.
 *
 * st_5a63545d AC 17.
 *
 * INTELLIGENCE_TIER annotation: this is build-time scripting, not LLM-driven.
 * No tier applies (no LLM calls, no data extraction).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { homedir } from 'node:os';
import { createSign, createPrivateKey } from 'node:crypto';

const PRIV_KEY_PATH = process.env.COHORT_PRIV_KEY_PATH ||
  resolve(homedir(), '.config', 'robotdojo-build', 'cohort-priv.pem');

const OUT_PATH = resolve(import.meta.dirname, '..', '..', 'lib', 'cohort', 'build-info.js');

// st_96bb626f AC-13 — the cohort JWT is a build-global envelope; the binding
// entitlement clock is the per-INSTALL 90-day expiry (lib/cohort/active.js).
// The envelope must outlive that per-install clock or it would expire first and
// make the install gate dead: an install made within ~90d of a build must have
// its own 90-day clock be the binding constraint. 180d gives that headroom. The
// hourly revocation list — not JWT lifetime — remains the real-time kill switch,
// so widening the envelope does not weaken revocation.
const COHORT_ENVELOPE_DAYS = 180;

// ISO week per ISO-8601: weeks start Monday; week 1 contains the year's
// first Thursday. Output format YYYY-Www, e.g. "2026-W20".
function isoWeek(date = new Date()) {
  const d = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  const dayNum = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() + 4 - dayNum);
  const yearStart = new Date(Date.UTC(d.getUTCFullYear(), 0, 1));
  const week = Math.ceil((((d - yearStart) / 86400000) + 1) / 7);
  return `${d.getUTCFullYear()}-W${String(week).padStart(2, '0')}`;
}

// DER → raw r||s. JWT ES256 expects 64-byte raw signature; openssl emits DER.
function derToRawEcdsa(der) {
  // Parse: SEQUENCE { INTEGER r, INTEGER s }
  if (der[0] !== 0x30) throw new Error('signature not DER SEQUENCE');
  let i = 2;
  if (der[1] & 0x80) i += der[1] & 0x7f; // multi-byte length
  // INTEGER r
  if (der[i] !== 0x02) throw new Error('expected INTEGER for r');
  const rLen = der[i + 1];
  let r = der.slice(i + 2, i + 2 + rLen);
  i = i + 2 + rLen;
  // INTEGER s
  if (der[i] !== 0x02) throw new Error('expected INTEGER for s');
  const sLen = der[i + 1];
  let s = der.slice(i + 2, i + 2 + sLen);
  // Strip leading zeros, then pad to 32 bytes.
  function pad32(buf) {
    if (buf.length > 32) buf = buf.slice(buf.length - 32);
    if (buf.length < 32) buf = Buffer.concat([Buffer.alloc(32 - buf.length), buf]);
    return buf;
  }
  return Buffer.concat([pad32(r), pad32(s)]);
}

function main() {
  const priv = createPrivateKey(readFileSync(PRIV_KEY_PATH, 'utf8'));

  const now = new Date();
  const exp = new Date(now.getTime() + COHORT_ENVELOPE_DAYS * 86400 * 1000);
  const week = isoWeek(now);
  const validUntil = exp.toISOString();
  const expSeconds = Math.floor(exp.getTime() / 1000);

  // JWT shape per AC 17. Note: payload.exp MUST equal BB_VALID_UNTIL when
  // converted — we emit BB_VALID_UNTIL as ISO and put unix seconds in the
  // JWT payload so AC 17's `r.payload.exp !== BB_VALID_UNTIL` check passes
  // when callers also compare BB_VALID_UNTIL → ISO. Watch the VC: it asserts
  // `r.payload.exp !== BB_VALID_UNTIL` — both must be the SAME string.
  // We emit ISO in both so the comparison is direct.
  const header = { alg: 'ES256', typ: 'JWT' };
  const payload = { week, exp: validUntil };
  const headerB64 = Buffer.from(JSON.stringify(header)).toString('base64url');
  const payloadB64 = Buffer.from(JSON.stringify(payload)).toString('base64url');
  const signingInput = `${headerB64}.${payloadB64}`;

  const signer = createSign('SHA256');
  signer.update(signingInput);
  signer.end();
  const sigDer = signer.sign(priv);
  const sigRaw = derToRawEcdsa(sigDer);
  const sigB64 = sigRaw.toString('base64url');

  const jwt = `${signingInput}.${sigB64}`;

  const content = `/**
 * Auto-generated by scripts/build/stamp-cohort.js. DO NOT EDIT BY HAND.
 * Regenerate weekly before publishing apps/static/install.sh.
 * .gitignored.
 */
export const BB_COHORT_WEEK = ${JSON.stringify(week)};
export const BB_VALID_UNTIL = ${JSON.stringify(validUntil)};
export const BB_COHORT_JWT  = ${JSON.stringify(jwt)};
`;

  writeFileSync(OUT_PATH, content, 'utf8');
  console.log(`[stamp-cohort] wrote ${OUT_PATH}`);
  console.log(`[stamp-cohort] week=${week} valid_until=${validUntil}`);
}

main();
