#!/usr/bin/env node
/**
 * scripts/check-agent-os.js — unified Agent OS install verifier (st_0c491456 Phase 3a).
 *
 * INTELLIGENCE_TIER: extraction (deterministic; no LLM)
 *
 * Replaces the patchwork of partial checks (check-skill-adapters.js +
 * check-identity-dist-fresh.js) with a single gate that asserts:
 *
 *   1. Skill adapters — every ~/.claude/skills/<skill>/SKILL.md is a live
 *      symlink (readlink -e resolves) pointing at the canonical
 *      ~/robotdojo/agents/skills/<skill>/SKILL.md.
 *   2. Claude agent adapters — every ~/.claude/agents/<Agent>.md is a live
 *      symlink to the canonical agents/dist/claude-agents/<Agent>.md.
 *   3. Codex adapter — ~/.codex/AGENTS.md is a live symlink to
 *      agents/dist/AGENTS.md.
 *   4. Cursor adapter — ~/.cursor/rules/identity.mdc is a live symlink to
 *      agents/dist/cursor-identity.mdc.
 *   5. Orphans / strays — any extra entry under those four install roots
 *      that does NOT correspond to a canonical source is a stray and fails.
 *      This catches:
 *        - ~/.claude/agents/teacher/ (no canonical source)
 *        - ~/.claude/skills/neon-postgres/ (frozen plain file)
 *        - ~/.claude/skills/{code-review.md,prd.md,product-review.md,…} loose root files
 *        - ~/.claude/plans (dangling symlink; must be removed, not repointed)
 *   6. DO-NOT-EDIT headers — every file under agents/dist/ begins with the
 *      generated-by header. Drift here means a hand edit slipped past review.
 *   7. Source→dist freshness — calls `generate-identity.js --check`. Any drift
 *      between persona sources and committed dist outputs fails the gate.
 *
 * Exit 0 = every adapter is a live symlink to canonical, no strays, headers
 *          present, sources match dist.
 * Exit 1 = at least one failure. The error message names each failure with the
 *          full path so the operator can act without a second grep.
 *
 * Wired into pre-commit (replacing the two old gates) and called as the final
 * self-verify step at the end of install-skills.sh.
 *
 * Run standalone: node ~/robotdojo/scripts/check-agent-os.js
 */

export const INTELLIGENCE_TIER = 'extraction';

import { readdirSync, lstatSync, existsSync, realpathSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';
import { spawnSync } from 'node:child_process';

const HOME = homedir();
const REPO_ROOT = join(HOME, 'robotdojo');
const CANON_SKILLS_DIR = join(REPO_ROOT, 'agents', 'skills');
const CANON_AGENTS_DIST_DIR = join(REPO_ROOT, 'agents', 'dist', 'claude-agents');
const CANON_AGENTS_DIST_AGENTS_MD = join(REPO_ROOT, 'agents', 'dist', 'AGENTS.md');
const CANON_AGENTS_DIST_CURSOR_MDC = join(REPO_ROOT, 'agents', 'dist', 'cursor-identity.mdc');
const CANON_DIST_DIR = join(REPO_ROOT, 'agents', 'dist');
const GENERATE_SCRIPT = join(REPO_ROOT, 'scripts', 'generate-identity.js');

const CLAUDE_SKILLS_DIR = join(HOME, '.claude', 'skills');
const CLAUDE_AGENTS_DIR = join(HOME, '.claude', 'agents');
const CLAUDE_PLANS_PATH = join(HOME, '.claude', 'plans');
const CODEX_AGENTS_MD = join(HOME, '.codex', 'AGENTS.md');
const CURSOR_RULES_DIR = join(HOME, '.cursor', 'rules');
const CURSOR_IDENTITY_MDC = join(CURSOR_RULES_DIR, 'identity.mdc');

const DO_NOT_EDIT_RE = /^<!-- Code generated by scripts\/generate-identity\.js — DO NOT EDIT\./;

// ── Helpers ──────────────────────────────────────────────────────────────────

// resolveSymlink: returns the absolute resolved target, or null if the link is
// missing, broken, or not a symlink. Mirrors `readlink -e` semantics — resolve
// only if the target exists. A symlink that exists but points at a missing
// file returns null (caught as "broken symlink").
function resolveSymlink(path) {
  let ls;
  try { ls = lstatSync(path); }
  catch { return { state: 'missing' }; }
  if (!ls.isSymbolicLink()) return { state: 'not-symlink', path };
  try {
    const resolved = realpathSync(path); // throws if target missing
    return { state: 'live', resolved };
  } catch {
    return { state: 'broken' };
  }
}

// isExternalSkill: an entry under ~/.claude/skills/ is an intentional
// cross-project install (NOT robotdojo drift) when it is a directory whose
// SKILL.md is a LIVE symlink resolving to a real file OUTSIDE the robotdojo
// repo tree — e.g. a skill owned by another of the user's projects. These are
// allowlisted so they do not fail the stray check. Loose files, broken/missing
// symlinks, and symlinks that resolve back INTO the robotdojo tree (a frozen
// copy or mis-link of a robotdojo skill) are NOT external and still fail.
let REPO_ROOT_REAL = REPO_ROOT;
try { REPO_ROOT_REAL = realpathSync(REPO_ROOT); } catch { /* keep literal */ }
function isExternalSkill(entry) {
  const dir = join(CLAUDE_SKILLS_DIR, entry);
  let st;
  try { st = lstatSync(dir); } catch { return false; }
  if (!st.isDirectory()) return false;
  const r = resolveSymlink(join(dir, 'SKILL.md'));
  if (r.state !== 'live') return false;
  return !r.resolved.startsWith(REPO_ROOT_REAL + '/');
}

function listSkillCanonical() {
  return readdirSync(CANON_SKILLS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((name) => existsSync(join(CANON_SKILLS_DIR, name, 'SKILL.md')))
    .sort();
}

function listAgentCanonical() {
  if (!existsSync(CANON_AGENTS_DIST_DIR)) return [];
  return readdirSync(CANON_AGENTS_DIST_DIR)
    .filter((n) => n.endsWith('.md'))
    .sort();
}

// ── Check 1: skill adapters ──────────────────────────────────────────────────

function checkSkills(failures) {
  if (!existsSync(CLAUDE_SKILLS_DIR)) return; // not installed — skip
  const canonical = listSkillCanonical();
  const canonicalSet = new Set(canonical);

  for (const skill of canonical) {
    const adapter = join(CLAUDE_SKILLS_DIR, skill, 'SKILL.md');
    const expected = realpathSync(join(CANON_SKILLS_DIR, skill, 'SKILL.md'));
    const r = resolveSymlink(adapter);
    if (r.state === 'missing') {
      failures.push(`skill "${skill}": adapter SKILL.md missing — run install-skills.sh`);
    } else if (r.state === 'not-symlink') {
      failures.push(`skill "${skill}": adapter is a PLAIN file (frozen copy), expected symlink to ${expected}`);
    } else if (r.state === 'broken') {
      failures.push(`skill "${skill}": adapter is a BROKEN symlink at ${adapter}`);
    } else if (r.resolved !== expected) {
      failures.push(`skill "${skill}": adapter resolves to ${r.resolved}, expected ${expected}`);
    }
  }

  // Stray detection: any entry in ~/.claude/skills/ that is neither a canonical
  // skill dir nor a hidden file is a stray. Loose files (code-review.md, prd.md,
  // etc.) and unrecognized dirs (neon-postgres) both fail here.
  for (const entry of readdirSync(CLAUDE_SKILLS_DIR)) {
    if (entry.startsWith('.')) continue; // .DS_Store etc.
    if (canonicalSet.has(entry)) {
      // canonical dir — already validated above
      continue;
    }
    if (isExternalSkill(entry)) {
      // intentional cross-project skill (SKILL.md symlinked outside robotdojo)
      continue;
    }
    failures.push(`stray under ~/.claude/skills/: ${entry} (no canonical source at agents/skills/${entry}/SKILL.md)`);
  }
}

// ── Check 2: Claude agent adapters ───────────────────────────────────────────

function checkAgents(failures) {
  if (!existsSync(CLAUDE_AGENTS_DIR)) return;
  const canonical = listAgentCanonical();
  const canonicalSet = new Set(canonical);

  for (const file of canonical) {
    const adapter = join(CLAUDE_AGENTS_DIR, file);
    const expected = realpathSync(join(CANON_AGENTS_DIST_DIR, file));
    const r = resolveSymlink(adapter);
    if (r.state === 'missing') {
      failures.push(`agent "${file}": adapter missing — run install-skills.sh`);
    } else if (r.state === 'not-symlink') {
      failures.push(`agent "${file}": adapter is a PLAIN file (frozen copy), expected symlink to ${expected}`);
    } else if (r.state === 'broken') {
      failures.push(`agent "${file}": adapter is a BROKEN symlink at ${adapter}`);
    } else if (r.resolved !== expected) {
      failures.push(`agent "${file}": adapter resolves to ${r.resolved}, expected ${expected}`);
    }
  }

  // Stray detection
  for (const entry of readdirSync(CLAUDE_AGENTS_DIR)) {
    if (entry.startsWith('.')) continue;
    if (canonicalSet.has(entry)) continue;
    failures.push(`stray under ~/.claude/agents/: ${entry} (no canonical source at agents/dist/claude-agents/${entry})`);
  }
}

// ── Check 3: dangling ~/.claude/plans (or any equivalent stray symlink) ──────

function checkClaudePlans(failures) {
  // ~/.claude/plans was historically a symlink to a now-retired top-level
  // dev-pipeline directory that no longer exists in the repo (st_9699c94f
  // moved that whole tree under user/workbenches/). The symlink target is
  // dangling. It must be removed entirely — not repointed. Any presence
  // (symlink, file, or directory) at that path is a failure: the path is
  // deprecated.
  let ls;
  try { ls = lstatSync(CLAUDE_PLANS_PATH); }
  catch { return; } // not present — clean

  if (ls.isSymbolicLink()) {
    failures.push(`stray ~/.claude/plans symlink exists (deprecated path; rm ~/.claude/plans)`);
  } else {
    failures.push(`stray ~/.claude/plans entry exists (deprecated path; remove it)`);
  }
}

// ── Check 4: Codex adapter ───────────────────────────────────────────────────

function checkCodex(failures) {
  if (!existsSync(join(HOME, '.codex'))) return;
  const r = resolveSymlink(CODEX_AGENTS_MD);
  if (r.state === 'missing') {
    failures.push(`codex: ~/.codex/AGENTS.md missing — run install-skills.sh`);
    return;
  }
  const expected = realpathSync(CANON_AGENTS_DIST_AGENTS_MD);
  if (r.state === 'not-symlink') {
    failures.push(`codex: ~/.codex/AGENTS.md is a PLAIN file, expected symlink to ${expected}`);
  } else if (r.state === 'broken') {
    failures.push(`codex: ~/.codex/AGENTS.md is a BROKEN symlink`);
  } else if (r.resolved !== expected) {
    failures.push(`codex: ~/.codex/AGENTS.md resolves to ${r.resolved}, expected ${expected}`);
  }
}

// ── Check 5b: Grok Build adapter ─────────────────────────────────────────────

function checkGrok(failures) {
  const grokRules = join(HOME, '.grok', 'rules');
  if (!existsSync(join(HOME, '.grok'))) return;
  if (!existsSync(grokRules)) {
    failures.push(`grok: ~/.grok/rules/ missing — run install-skills.sh`);
    return;
  }
  const adapter = join(grokRules, 'robotdojo-identity.md');
  const expectedPath = join(CANON_DIST_DIR, 'grok.md');
  if (!existsSync(expectedPath)) {
    failures.push(`grok: agents/dist/grok.md missing — run generate-identity.js`);
    return;
  }
  const expected = realpathSync(expectedPath);
  const r = resolveSymlink(adapter);
  if (r.state === 'missing') {
    failures.push(`grok: ~/.grok/rules/robotdojo-identity.md missing — run install-skills.sh`);
  } else if (r.state === 'not-symlink') {
    failures.push(`grok: robotdojo-identity.md is a PLAIN file, expected symlink to ${expected}`);
  } else if (r.state === 'broken') {
    failures.push(`grok: robotdojo-identity.md is a BROKEN symlink`);
  } else if (r.resolved !== expected) {
    failures.push(`grok: robotdojo-identity.md resolves to ${r.resolved}, expected ${expected}`);
  }
}

// ── Check 5: Cursor adapter ──────────────────────────────────────────────────

function checkCursor(failures) {
  if (!existsSync(CURSOR_RULES_DIR)) return;
  // identity.mdc must exist as a live symlink to dist
  const r = resolveSymlink(CURSOR_IDENTITY_MDC);
  if (r.state === 'missing') {
    failures.push(`cursor: ~/.cursor/rules/identity.mdc missing — run install-skills.sh`);
    return;
  }
  const expected = realpathSync(CANON_AGENTS_DIST_CURSOR_MDC);
  if (r.state === 'not-symlink') {
    failures.push(`cursor: ~/.cursor/rules/identity.mdc is a PLAIN file, expected symlink to ${expected}`);
  } else if (r.state === 'broken') {
    failures.push(`cursor: ~/.cursor/rules/identity.mdc is a BROKEN symlink`);
  } else if (r.resolved !== expected) {
    failures.push(`cursor: ~/.cursor/rules/identity.mdc resolves to ${r.resolved}, expected ${expected}`);
  }
}

// ── Check 6: DO-NOT-EDIT headers on every dist file ──────────────────────────

function checkDistHeaders(failures) {
  if (!existsSync(CANON_DIST_DIR)) {
    failures.push(`agents/dist/ missing — run node scripts/generate-identity.js`);
    return;
  }
  // Walk all regular files under dist/, including claude-agents/*.md and
  // cursor-memory.mdc. Skip backup files (*.bak-*) since those are archival,
  // not consumed by any IDE.
  const stack = [CANON_DIST_DIR];
  while (stack.length > 0) {
    const dir = stack.pop();
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, e.name);
      if (e.isDirectory()) { stack.push(full); continue; }
      if (!e.isFile()) continue;
      if (e.name.includes('.bak-')) continue;
      const content = readFileSync(full, 'utf8');
      const head = content.slice(0, 400);
      let hasHeader = DO_NOT_EDIT_RE.test(head);
      if (!hasHeader && e.name.endsWith('.mdc') && content.startsWith('---\n')) {
        const end = content.indexOf('\n---\n', 4);
        if (end >= 0) {
          const afterFrontmatter = content.slice(end + '\n---\n'.length, end + '\n---\n'.length + 200);
          hasHeader = DO_NOT_EDIT_RE.test(afterFrontmatter);
        }
      }
      if (!hasHeader) {
        failures.push(`agents/dist header missing: ${full} — generated files must include the DO-NOT-EDIT banner`);
      }
    }
  }
}

// ── Check 7: source→dist freshness via generate-identity.js --check ──────────

function checkFreshness(failures) {
  const result = spawnSync(process.execPath, [GENERATE_SCRIPT, '--check'], {
    encoding: 'utf8',
  });
  if (result.status !== 0) {
    // Surface the subprocess's stderr so the operator sees which file drifted.
    const out = (result.stdout || '') + (result.stderr || '');
    failures.push(`source→dist freshness drift:\n${out.trim().split('\n').map((l) => '    ' + l).join('\n')}`);
  }
}

// ── Main ─────────────────────────────────────────────────────────────────────

function main() {
  const failures = [];
  checkSkills(failures);
  checkAgents(failures);
  checkClaudePlans(failures);
  checkCodex(failures);
  checkCursor(failures);
  checkGrok(failures);
  checkDistHeaders(failures);
  checkFreshness(failures);

  if (failures.length > 0) {
    console.error('[check-agent-os] FAIL — agent OS install state has drift:');
    for (const f of failures) console.error(`  - ${f}`);
    console.error('\nFix: bash ~/robotdojo/scripts/install-skills.sh');
    process.exit(1);
  }
  console.log('[check-agent-os] OK — every adapter is a live symlink to canonical; dist headers present; sources match dist');
  process.exit(0);
}

main();
